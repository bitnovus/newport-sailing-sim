import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outputPath = join(root, "public", "THIRD_PARTY_LICENSES.txt");
const npmCommand = process.platform === "win32" ? "npm.cmd" : "npm";

const listedPaths = execFileSync(
  npmCommand,
  ["ls", "--omit=dev", "--all", "--parseable"],
  { cwd: root, encoding: "utf8" },
)
  .trim()
  .split(/\r?\n/)
  .filter((path) => path && resolve(path) !== root);

const packages = listedPaths.map((packagePath) => {
  const manifest = JSON.parse(readFileSync(join(packagePath, "package.json"), "utf8"));
  const noticeFiles = readdirSync(packagePath)
    .filter((name) => /^(licen[cs]e|copying|notice)(\..*)?$/i.test(name))
    .sort((a, b) => a.localeCompare(b));

  let notices = noticeFiles.map((name) => ({
    name,
    text: readFileSync(join(packagePath, name), "utf8").trim(),
  }));

  // murmurhash-js declares MIT but ships its license in the README.
  if (notices.length === 0) {
    const readmeName = readdirSync(packagePath).find((name) => /^readme(\..*)?$/i.test(name));
    if (readmeName) {
      const readme = readFileSync(join(packagePath, readmeName), "utf8");
      const licenseStart = readme.search(/^##?\s+License\b/im);
      if (licenseStart >= 0) {
        notices = [{ name: `${readmeName} license section`, text: readme.slice(licenseStart).trim() }];
      }
    }
  }

  if (notices.length === 0) {
    throw new Error(`${manifest.name}@${manifest.version} has no distributable license text`);
  }

  return {
    name: manifest.name,
    version: manifest.version,
    license: manifest.license ?? "not declared",
    notices,
  };
});

packages.sort((a, b) =>
  `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`),
);

const sections = packages.map(({ name, version, license, notices }) => {
  const title = `${name}@${version}`;
  const noticeText = notices
    .map(({ name: fileName, text }) => `Source file: ${fileName}\n\n${text}`)
    .join("\n\n");
  return `${title}\n${"-".repeat(title.length)}\nSPDX license: ${license}\n\n${noticeText}`;
});

const output = [
  "Runtime dependency license notices",
  "==================================",
  "",
  "Generated by scripts/generate-third-party-licenses.mjs from the production",
  "dependency tree in package-lock.json. Do not edit this file by hand.",
  "",
  ...sections.flatMap((section) => [section, ""]),
].join("\n");

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== output) {
    console.error("public/THIRD_PARTY_LICENSES.txt is stale; run npm run licenses:generate");
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${packages.length} runtime package notices to ${outputPath}`);
}
